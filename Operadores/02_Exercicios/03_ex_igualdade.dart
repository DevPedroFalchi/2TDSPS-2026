// Operadores relacionais de comparação

void main(){

  //Dois valores para comparar entre si
  final int valor1 = 10;
  final int valor2 = 2;

  // == verifica igualdade
  // != verifica a diferença ou desigualdade

  print(valor1 == valor2);
  print(valor1 != valor2);
  print('valor1 == valor2: ${valor1 == valor2}');
  print('valor1 != valor2: ${valor1 != valor2}');



}