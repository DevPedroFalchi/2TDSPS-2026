// Exercicio classificação numérica
void main() {
  var numero = 7; //Definindo o valor do numero a ser verificado

  if (numero > 0) {
    //Verifica se o numero é maior que zero
    print('O numero é positivo');
  } else if (numero < 0) {
    //verifica se é menor que zero
    print('O numero é negativo');
  } else {
    //se nenhuma das condicoes anteriores for verdadeira, imprime essa mensagem
    print('O numero é zero');
  }
}
